def ensure_main(db) -> dict:
    """Idempotently provision Blinks Bright + a showcase demo dataset."""
    existing = db.query(models.Clinic).filter_by(slug=SLUG).first()
    if existing:
        return {"created": False, "clinic_id": existing.id}

    clinic = provision_clinic(
        db, CLINIC["name"], slug=CLINIC["slug"], tagline=CLINIC["tagline"],
        logo=CLINIC["logo"], accent=CLINIC["accent"], branches=CLINIC["branches"],
        services=SERVICES, kb=_main_kb(), promos=PROMOS, doctors=DOCTORS,
    )
    db.flush()
    staff = _staff(db, clinic, demo_logins=True)
    _seed_clinic_demo(db, clinic, staff, scale=0.3)
    db.commit()

    from app.ai.rag import reindex
    return {"created": True, "clinic_id": clinic.id, "index": reindex(db, clinic_id=clinic.id)}


def main() -> None:
    db = SessionLocal()
    try:
        print("[seed_main]", ensure_main(db))
    finally:
        db.close()


if __name__ == "__main__":
    main()
